  var current = 'es';

  function detect(saved) {
    if (saved && STRINGS[saved]) return saved;
    var nav = (root.navigator && root.navigator.language) || 'es';
    return nav.toLowerCase().indexOf('es') === 0 ? 'es' : 'en';
  }
  function setLang(lang) { if (STRINGS[lang]) current = lang; }
  function t(key, params) {
    var s = STRINGS[current][key];
    if (s === undefined) s = STRINGS.es[key];
    if (s === undefined) s = key;
    if (params) Object.keys(params).forEach(function (k) { s = s.split('{' + k + '}').join(String(params[k])); });
    return s;
  }

  var api = { STRINGS: STRINGS, t: t, setLang: setLang, detect: detect, get lang() { return current; } };
  root.StudyDesk = root.StudyDesk || {};
  root.StudyDesk.i18n = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
